// Helper functions for storage & resetting
const POKEMON_STORAGE_KEY = 'pokemon_raid_wheel_v2';

function loadPokemon() {
    try {
        const saved = localStorage.getItem(POKEMON_STORAGE_KEY);
        if (saved) {
            const parsed = JSON.parse(saved);
            if (Array.isArray(parsed) && parsed.length >= 45) return parsed;
        }
    } catch (e) {
        console.warn('Failed to load Pokémon from localStorage:', e);
    }
    savePokemon(POKEMON_ROSTER);
    return [...POKEMON_ROSTER];
}

function savePokemon(roster) {
    try {
        localStorage.setItem(POKEMON_STORAGE_KEY, JSON.stringify(roster));
    } catch (e) {
        console.warn('Failed to save Pokémon:', e);
    }
}

function resetPokemonToDefault() {
    localStorage.removeItem(POKEMON_STORAGE_KEY);
    ['pokemon_raid_wheel_v1'].forEach(k => {
        try { localStorage.removeItem(k); } catch(e) {}
    });
    savePokemon(POKEMON_ROSTER);
    return [...POKEMON_ROSTER];
}
